# photos: landscape + portrait + one with EXIF orientation 6
random.seed(7)
def photo(name, w, h, hue, text):
    im = Image.new('RGB', (w, h)); px = im.load()
    for y in range(h):
        for x in range(w):
            px[x, y] = (int(120 + 100 * x / w * hue[0]), int(120 + 100 * y / h * hue[1]), int(110 + 80 * hue[2]))
    d = ImageDraw.Draw(im)
    for _ in range(14):  # crack-like lines
        x, y = random.randint(0, w), random.randint(0, h)
        for _ in range(30):
            nx, ny = x + random.randint(-14, 14), y + random.randint(0, 18)
            d.line([(x, y), (nx, ny)], fill=(40, 30, 30), width=3); x, y = nx, ny
    d.text((w // 2, h // 2), text, fill='white', font=FB, anchor='mm')
    return im

from PIL import Image, ImageDraw, ImageFont
import os, random
OUT = os.path.join(os.path.dirname(__file__), '..', 'public', 'demo')
os.makedirs(OUT, exist_ok=True)
try:
    F = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 28)
    FB = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 44)
except Exception:
    F = FB = ImageFont.load_default()

def plan(name, w, h, rooms, label):
    im = Image.new('RGB', (w, h), 'white'); d = ImageDraw.Draw(im)
    for x in range(0, w, 100): d.line([(x, 0), (x, h)], fill=(235, 238, 245), width=1)
    for y in range(0, h, 100): d.line([(0, y), (w, y)], fill=(235, 238, 245), width=1)
    d.rectangle([20, 20, w - 20, h - 20], outline=(30, 30, 30), width=12)
    for (x1, y1, x2, y2, t) in rooms:
        X1, Y1, X2, Y2 = int(x1 * w), int(y1 * h), int(x2 * w), int(y2 * h)
        d.rectangle([X1, Y1, X2, Y2], outline=(60, 60, 60), width=6, fill=(250, 248, 240))
        d.text(((X1 + X2) // 2, (Y1 + Y2) // 2), t, fill=(90, 90, 90), font=F, anchor='mm')
    d.text((60, 50), f'SYNTHETIC PLAN - {label}', fill=(180, 30, 30), font=FB)
    d.text((w - 60, h - 50), 'corner marker', fill=(120, 120, 120), font=F, anchor='rd')
    for (cx, cy) in ((40, 40), (w - 40, 40), (40, h - 40), (w - 40, h - 40)):
        d.ellipse([cx - 14, cy - 14, cx + 14, cy + 14], fill=(30, 100, 200))
    im.save(os.path.join(OUT, name)); return im

